# 산술연산자
a1=int(input('정수 입력 : '))
a2=int(input('정수 입력 : '))

b1=a1+a2
print(f'{a1}+{a2}={b1}')

b2=a1-a2
print(f'{a1}-{a2}={b2}')

b3=a1*a2
print(f'{a1}*{a2}={b3}')

b4=a1/a2
print(f'{a1}/{a2}={b4}')

b5=a1%a2
print(f'{a1}%{a2}={b5}')

b6=a1//a2
print(f'{a1}//{a2}={b6}')

b7=a1**a2
print(f'{a1}**{a2}={b7}')