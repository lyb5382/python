# 5자리 확보 후, 왼쪽을 붙이기 (왼쪽 정렬)
a='{0:<5d}'.format(200) # 200 왼쪽 정렬 출력
print(a+'휴')

# 5자리 확보 후, 오른쪽을 붙이기 (우 정렬)
b='{0:>5d}'.format(200)
print(b)

# 5자리 확보 후, 가운데 정렬
c='{0:^5d}'.format(200)
print(c)

# 5자리 확보 후, 빈 공간을 0으로 채우고 오른쪽 정렬
d='{0:>05d}'.format(200)
print(d)

e='{0:!<5d}'.format(200) # 빈칸 느낌표로 채우기 숫자는 <이거 뒤에
print(e)

f='{0:=^5d}'.format(200)
print(f)

g='{0:*^5d}, {1:.2f}'.format(10, 200.002)
print(g)